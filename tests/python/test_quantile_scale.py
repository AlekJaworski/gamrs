"""Parity tier — a quantile fit must not depend on the units of y.

The fixture (`tests/fixtures/1d_quantile_price_scale_n600_k10_cr.json`,
generated by `scripts/r/gen_quantile_price_scale_fixture.R`) is a synthetic
housing-price series in raw dollars with qgam's median at six dates. A
quantile is equivariant to positive rescaling, so fitting `c·y` and dividing
the prediction by `c` must give the same curve for any `c`, and that curve
must match qgam's.
"""

from __future__ import annotations

import numpy as np
import pytest

import gamrs

from conftest import load_fixture

pytestmark = pytest.mark.parity


@pytest.mark.parametrize("preset", [None, "fast_oos"])
def test_quantile_fit_is_scale_equivariant_and_matches_qgam(preset):
    fx = load_fixture("1d_quantile_price_scale_n600_k10_cr")
    x = np.asarray(fx["inputs"]["x_train"], dtype=np.float64).reshape(-1, 1)
    y = np.asarray(fx["inputs"]["y_train"], dtype=np.float64)
    x_eval = np.asarray(fx["inputs"]["x_eval"], dtype=np.float64).reshape(-1, 1)
    ref = np.asarray(fx["qgam_output"]["pred_eval"], dtype=np.float64)

    preds = {
        c: np.asarray(gamrs.fit_quantile(x, c * y, tau=0.5, k=10, preset=preset).predict(x_eval)) / c
        for c in (1e-5, 1.0, 1e5)
    }
    for c, pred in preds.items():
        np.testing.assert_allclose(pred, preds[1.0], rtol=1e-6, err_msg=f"c={c}")
    if preset is None:
        np.testing.assert_allclose(preds[1.0], ref, rtol=0.02)
